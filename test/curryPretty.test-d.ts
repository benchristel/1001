import {expectType} from "tsd"
import {curryPretty} from "../src/index.js"

const f12 = curryPretty("", (a: 1, b: 2): true => true)
const f123 = curryPretty("", (a: 1, b: 2, c: 3): true => true)
const f1234 = curryPretty("", (a: 1, b: 2, c: 3, d: 4): true => true)
const f12345 = curryPretty("", (a: 1, b: 2, c: 3, d: 4, e: 5): true => true)

expectType<true>(f12(1, 2))
expectType<true>(f12(1)(2))

expectType<true>(f123(1, 2, 3))
expectType<true>(f123(1, 2)(3))
expectType<true>(f123(1)(2, 3))
expectType<true>(f123(1)(2)(3))

expectType<true>(f1234(1, 2, 3, 4))
expectType<true>(f1234(1, 2, 3)(4))
expectType<true>(f1234(1, 2)(3, 4))
expectType<true>(f1234(1, 2)(3)(4))
expectType<true>(f1234(1)(2, 3, 4))
expectType<true>(f1234(1)(2, 3)(4))
expectType<true>(f1234(1)(2)(3, 4))
expectType<true>(f1234(1)(2)(3)(4))

expectType<true>(f12345(1, 2, 3, 4, 5))
expectType<true>(f12345(1, 2, 3, 4)(5))
expectType<true>(f12345(1, 2, 3)(4, 5))
expectType<true>(f12345(1, 2, 3)(4)(5))
expectType<true>(f12345(1, 2)(3, 4, 5))
expectType<true>(f12345(1, 2)(3, 4)(5))
expectType<true>(f12345(1, 2)(3)(4, 5))
expectType<true>(f12345(1, 2)(3)(4)(5))
expectType<true>(f12345(1)(2, 3, 4, 5))
expectType<true>(f12345(1)(2, 3, 4)(5))
expectType<true>(f12345(1)(2, 3)(4, 5))
expectType<true>(f12345(1)(2, 3)(4)(5))
expectType<true>(f12345(1)(2)(3, 4, 5))
expectType<true>(f12345(1)(2)(3, 4)(5))
expectType<true>(f12345(1)(2)(3)(4, 5))
expectType<true>(f12345(1)(2)(3)(4)(5))
